def clean_name(value):
    value = re.sub(r'\s*·\s*[1-5]/\S+(?=\s+\(уточнить\)|$)', '', value)
    return value.replace(' (уточнить)', '').strip()


def canonical_catalog(items, mapping, groups):
    originals = {item['source_key']: item for item in items}
    members = [key for group in groups for key in group['members']]
    assert len(members) == len(set(members)) and set(members) == set(originals)
    output, remap, provenance = [], {}, []
    for group in groups:
        assert group['keep'] in group['members']
        item = copy.deepcopy(originals[group['keep']])
        old_name = clean_name(item['name'])
        name = group['name'].strip()
        needs_review = '(уточнить)' in item['name']
        traditional_family = any(name.startswith(known) for known in TRADITIONAL)
        neutral_rename = old_name != name and not traditional_family
        aliases = []
        if not neutral_rename:
            for key in group['members']:
                source = originals[key]
                for alias in [clean_name(source['name']), *source.get('aliases', [])]:
                    if alias and alias != name and alias.casefold() not in {a.casefold() for a in aliases}:
                        aliases.append(alias)
        item['name'] = name + (' (уточнить)' if needs_review else '')
        item['aliases'] = aliases[:20]
        if neutral_rename:
            item.pop('sanskrit_cyrillic', None)
            item.pop('sanskrit_latin', None)
            item['alternate_name'] = None
            description, cues, benefits, precautions, facets = profile(name)
            item.update(information_description=description, teacher_cues=cues, benefits=benefits,
                        precautions=precautions, facet_keys=facets)
        source_notes = [originals[key]['editorial']['source'].split(': ', 1)[-1] for key in group['members']]
        item['editorial']['source'] = 'Оригинальные листы владельца: ' + '; '.join(source_notes)
        item['editorial']['review_note'] = ('Визуально объединены одинаковые позы с разных листов. ' + group['reason'] +
            ' Исходные изображения всех вхождений сохранены в практиках. Справка вводная; методическая проверка не заявлена.')
        output.append(item)
        for key in group['members']:
            remap[key] = group['keep']
        provenance.append({'source_key': group['keep'], 'name': item['name'],
                           'selected': group['keep'].removeprefix('spinal-five-v1:'),
                           'occurrences': [key.removeprefix('spinal-five-v1:') for key in group['members']]})
    return output, {occurrence: remap[key] for occurrence, key in mapping.items()}, provenance


